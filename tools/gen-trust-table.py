#!/usr/bin/env python3
"""The firmware's trust table, generated from keys/release-keys.txt at build time (task p1.15-58).

    python tools/gen-trust-table.py keys/release-keys.txt <out>/trust_keys.h
    python tools/gen-trust-table.py keys/release-keys.txt <out>/trust_keys.h --test-key

Writes a C++ header naming the public keys this build trusts a release manifest to be signed with,
each with its key id (FIRMWARE-MANIFEST.md section 3: room for three). It is included by exactly
one translation unit, src/update/Trust.cpp, and tools/pio/release_headers.py runs it before every
build of every environment - so the file a release is verified against and the table a board
checks an update with are the same file, read by the same loader
(tools/release/verify_release.py's `load_keys`).

`--test-key` appends the specification's public test key, read from the fixtures that publish it
(tests/fixtures/firmware/TEST-KEY.txt) rather than written down here, and marks the table. **That
is a test build**: [env:native] and nothing else. A board environment never passes it, the release
tooling refuses to publish an image whose bytes carry that key, and a release build whose trust
table would hold it is refused here before a single file is compiled.

Standard library only, and deterministic: the same inputs give the same bytes, and the file is
rewritten only when it changed, so an unchanged table does not rebuild what includes it.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(HERE, "release"))

import manifest as mf  # noqa: E402  tools/release/manifest.py
import verify_release  # noqa: E402  tools/release/verify_release.py: load_keys, MAX_KEYS
from manifest import Refused  # noqa: E402

MAX_KEYS = verify_release.MAX_KEYS
FIXTURES = os.path.join(REPO, "tests", "fixtures", "firmware")


def c_bytes(data):
    return ", ".join("0x%02x" % b for b in data)


def render(keys, trusts_test_key, source):
    if len(keys) > MAX_KEYS:
        raise Refused("%d keys; a build has room for %d (FIRMWARE-MANIFEST.md section 3)"
                      % (len(keys), MAX_KEYS))
    lines = [
        "// Generated by tools/gen-trust-table.py from %s." % source,
        "// Do not edit and do not commit: every build rewrites it (tools/pio/release_headers.py).",
        "//",
        "// The public keys this build trusts a release manifest to be signed with, each with its",
        "// key id (FIRMWARE-MANIFEST.md section 3). Unused rows are zero; kTrustedKeyCount says how",
        "// many are real. kTrustsTestKey is true only in a test build - [env:native], whose tests",
        "// sign with the key the specification publishes on purpose.",
        "//",
        "// Included by src/update/Trust.cpp and by nothing else, after Trust.h, which declares",
        "// TrustedKey and kMaxTrustedKeys: this file names no include of its own so that it needs",
        "// no include path but its own directory's.",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "",
        "namespace mm {",
        "namespace update {",
        "namespace generated {",
        "",
        "static const size_t kTrustedKeyCount = %d;" % len(keys),
        "static const bool kTrustsTestKey = %s;" % ("true" if trusts_test_key else "false"),
        "",
        "static const TrustedKey kTrustedKeys[kMaxTrustedKeys] = {",
    ]
    for i in range(MAX_KEYS):
        if i < len(keys):
            key = keys[i]
            lines.append("    // key id %s" % mf.key_id(key))
            lines.append("    {{%s}," % c_bytes(bytes.fromhex(mf.key_id(key))))
            lines.append("     {%s}}," % c_bytes(key))
        else:
            lines.append("    {{0, 0, 0, 0, 0, 0, 0, 0}, {0}},  // unused")
    lines += [
        "};",
        "",
        "}  // namespace generated",
        "}  // namespace update",
        "}  // namespace mm",
    ]
    return "\n".join(lines) + "\n"


def generate(keys_path, test_build):
    keys = verify_release.load_keys(keys_path, test_build=test_build)
    source = os.path.relpath(keys_path, REPO).replace("\\", "/")
    if test_build:
        test_key = mf.test_public_key(FIXTURES)
        if test_key not in keys:
            keys.append(test_key)
        source += " + the test key of tests/fixtures/firmware/TEST-KEY.txt"
    return render(keys, test_build, source)


def write(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    if os.path.isfile(path):
        with open(path, "r", encoding="ascii", newline="") as fh:
            if fh.read() == text:
                return False
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)
    return True


def main(argv):
    args = [a for a in argv[1:] if a != "--test-key"]
    test_build = "--test-key" in argv[1:]
    if len(args) != 2:
        print(__doc__)
        return 2
    try:
        text = generate(args[0], test_build)
    except Refused as exc:
        print("REFUSED: %s" % exc, file=sys.stderr)
        return 1
    write(args[1], text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
