# The two generated headers of src/update/, written before every build (task p1.15-58). A `pre:`
# script of every environment.
#
#   src/update/generated/trust_keys.h        the public keys this build trusts a release manifest
#                                            to be signed with, from keys/release-keys.txt
#                                            (tools/gen-trust-table.py). [env:native] is a TEST
#                                            BUILD and gets the specification's test key too; no
#                                            board environment ever does.
#   src/update/generated/image_descriptor.h  the 96 bytes of FIRMWARE-MANIFEST.md section 4 that
#                                            this image carries about itself: the role byte 32,
#                                            the board, the band and the version this build was
#                                            given. Board environments only - [env:native] builds
#                                            no image. tools/release/manifest.py makes the bytes,
#                                            the same function the release tooling writes the
#                                            manifest with, so the descriptor in the image and the
#                                            entry above it cannot be made by two different ideas
#                                            of section 4.
#
# They are written into the source tree, git-ignored, rather than into the build directory, because
# with `framework = arduino, espidf` src/ is compiled from the CMake code model and an include
# directory added to this SCons environment does not reliably reach it (tools/pio/arduino_component.py
# says more about that). A header beside the file that includes it needs no include path at all.
#
# The version is read from the build's own MESHMASTER_AGENT_VERSION define, which
# .github/workflows/release.yml sets and which src/version.cpp reports - so the string inside the
# image and the string the board prints are one string. With no define it is 0.0.0-dev, exactly as
# version.cpp defaults it.

import os
import re
import subprocess
import sys

Import("env")  # noqa: F821  (SCons injects it)

project = env.subst("$PROJECT_DIR")
pioenv = env.subst("$PIOENV")
generated = os.path.join(project, "src", "update", "generated")
tools = os.path.join(project, "tools")
sys.path.insert(0, os.path.join(tools, "release"))

import manifest as mf  # noqa: E402  tools/release/manifest.py

ROLE = "exit-node"
BAND = "868"
FALLBACK_VERSION = "0.0.0-dev"  # src/version.cpp's own default


def defined(name, fallback):
    """A `-D <name>='"<text>"'` of this environment, with its quotes taken off.

    Read out of BUILD_FLAGS, not out of CPPDEFINES: a `pre:` script runs before PlatformIO has
    parsed the flags into defines, so CPPDEFINES is still None here. BUILD_FLAGS is the raw list,
    platformio.ini's own flags first and the PLATFORMIO_BUILD_FLAGS of the environment last - which
    is how .github/workflows/release.yml hands the version in, so the last match is the one."""
    text = " ".join(env.get("BUILD_FLAGS") or [])
    found = re.findall(r"-D\s*%s=(\S+)" % re.escape(name), text)
    if not found:
        return fallback
    return found[-1].strip("'").strip('"')


def run(args):
    result = subprocess.run([env.subst("$PYTHONEXE")] + args, cwd=project)
    if result.returncode != 0:
        raise Exception("release_headers: %s failed with %d" % (args[0], result.returncode))


# ---------------------------------------------------------------- the trust table
keys_file = os.path.join(project, "keys", "release-keys.txt")
args = [os.path.join(tools, "gen-trust-table.py"), keys_file,
        os.path.join(generated, "trust_keys.h")]
if pioenv == "native":
    args.append("--test-key")
run(args)
print("release_headers: trust_keys.h from keys/release-keys.txt%s"
      % (" + the specification's test key (a test build)" if pioenv == "native" else ""))

# ---------------------------------------------------------------- the descriptor in the image
if pioenv != "native":
    version = defined("MESHMASTER_AGENT_VERSION", FALLBACK_VERSION)
    board = defined("MESHMASTER_BOARD", pioenv)
    blob = mf.make_descriptor(ROLE, version, board, BAND)
    lines = [
        "// Generated by tools/pio/release_headers.py from tools/release/manifest.py.",
        "// Do not edit and do not commit: every build rewrites it.",
        "//",
        "// The 96 bytes of FIRMWARE-MANIFEST.md section 4 that this image carries about itself:",
        "//   role %d (%s), slot 0xFF (any), link 0.0, version %s, board %s, band %s"
        % (mf.ROLES[ROLE], ROLE, version, board, BAND),
        "// Included by src/update/ImageDescriptor.cpp and by nothing else.",
        "#pragma once",
        "",
        "#define MESHMASTER_IMAGE_DESCRIPTOR_BYTES \\",
    ]
    rows = [", ".join("0x%02x" % b for b in blob[at:at + 12]) for at in range(0, len(blob), 12)]
    lines += ["  " + row + (", \\" if i + 1 < len(rows) else "") for i, row in enumerate(rows)]
    text = "\n".join(lines) + "\n"
    os.makedirs(generated, exist_ok=True)
    path = os.path.join(generated, "image_descriptor.h")
    if not (os.path.isfile(path) and open(path, "r", newline="").read() == text):
        with open(path, "w", encoding="ascii", newline="\n") as fh:
            fh.write(text)
    print("release_headers: image_descriptor.h for %s %s, band %s, role %s"
          % (board, version, BAND, ROLE))
